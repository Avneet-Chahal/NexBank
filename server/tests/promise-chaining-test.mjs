import { processTransactionAuditPipeline } from "../src/utils/promiseChainingDemo.js";

async function runTests() {
  console.log("[TEST] Testing Topic 4: Explicit Promise Chaining (.then().then().catch())...");

  let passed = 0;
  let failed = 0;

  function assert(condition, message) {
    if (condition) {
      console.log(` PASS: ${message}`);
      passed++;
    } else {
      console.error(` FAIL: ${message}`);
      failed++;
    }
  }

  // Case 1: Valid transaction successfully completes .then().then() chain
  const validTx = { title: "Salary Payout", amount: 50000, type: "income" };
  const resSuccess = await processTransactionAuditPipeline(validTx);
  assert(resSuccess.success === true, "Valid transaction succeeds through promise chain");
  assert(resSuccess.receipt && resSuccess.receipt.isCompliant === true, "Audit receipt generated by second .then()");
  assert(resSuccess.receipt.transaction.complianceStatus === "VERIFIED_AML_CLEARED", "Enrichment verified by first .then()");

  // Case 2: Expense transaction calculates regulatory audit fee
  const expenseTx = { title: "Equipment Purchase", amount: 20000, type: "expense" };
  const resExpense = await processTransactionAuditPipeline(expenseTx);
  assert(resExpense.success === true && resExpense.receipt.transaction.auditFee === 20.0, "Expense fee calculated in chain");

  // Case 3: Invalid transaction caught by .catch()
  const invalidTx = { title: "Bad Transfer", amount: -500, type: "expense" };
  const resError = await processTransactionAuditPipeline(invalidTx);
  assert(resError.success === false, "Negative amount triggers promise rejection");
  assert(resError.error.includes("Valid positive transaction amount is required"), "Error message caught by .catch()");

  // Case 4: Invalid type caught by .catch()
  const invalidTypeTx = { title: "Transfer", amount: 500, type: "unknown" };
  const resTypeError = await processTransactionAuditPipeline(invalidTypeTx);
  assert(resTypeError.success === false, "Invalid type triggers promise rejection");
  assert(resTypeError.error.includes("Transaction type must be 'income' or 'expense'"), "Type error caught by .catch()");

  console.log(`\n--- Promise Chaining Test Summary ---`);
  console.log(`Passed: ${passed}, Failed: ${failed}`);
  process.exit(failed > 0 ? 1 : 0);
}

runTests().catch((err) => {
  console.error("Test failed:", err);
  process.exit(1);
});
